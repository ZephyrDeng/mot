/**
 * Slack app manifest generator.
 *
 * One Slack app can only feed one gateway (Socket Mode splits events across
 * connections), so each machine running mot needs its own app. This builds the
 * same manifest as the shipped `manifest.yaml`, with a custom app name, bot
 * name, and slash command so several apps can live in one workspace.
 *
 * Keep the output in sync with manifest.yaml (test/manifest.test.ts checks it).
 */

import { normalizeSlashCommand, validateSlashCommand } from './config.js';

export interface ManifestOptions {
  /** App name shown in Slack (max 35 chars). Default: Mot */
  name?: string;
  /** Bot display name (lowercase letters, digits, "-", "_", "."). Default: derived from `name` */
  botName?: string;
  /** Slash command, with or without the leading "/". Default: /mot */
  command?: string;
}

const MAX_APP_NAME_LENGTH = 35;
const BOT_NAME_PATTERN = /^[a-z0-9._-]{1,80}$/;

/** Derive a valid bot display name from an app name: "Mot MacBook" → "mot-macbook". */
export function deriveBotName(appName: string): string {
  return appName
    .trim()
    .toLowerCase()
    .replace(/\s+/g, '-')
    .replace(/[^a-z0-9._-]/g, '');
}

/** Plain scalar when it is obviously safe, otherwise a JSON (= valid YAML) double-quoted string. */
function yamlScalar(value: string): string {
  return /^[A-Za-z0-9][A-Za-z0-9 _./()-]*$/.test(value) && !value.endsWith(' ')
    ? value
    : JSON.stringify(value);
}

export function buildManifest(options: ManifestOptions = {}): string {
  const name = (options.name ?? 'Mot').trim();
  if (!name) throw new Error('--name cannot be empty.');
  if (name.length > MAX_APP_NAME_LENGTH) {
    throw new Error(`--name must be at most ${MAX_APP_NAME_LENGTH} characters.`);
  }

  const botName = (options.botName ?? deriveBotName(name)).trim();
  if (!BOT_NAME_PATTERN.test(botName)) {
    throw new Error(
      '--bot-name must use lowercase letters, digits, ".", "-" or "_" (max 80 characters). ' +
        'Pass --bot-name explicitly when --name has no usable characters.',
    );
  }

  const command = normalizeSlashCommand(options.command ?? '/mot');
  const commandProblems = validateSlashCommand(command);
  if (commandProblems.length > 0) throw new Error(commandProblems.join(' '));

  return [
    `# Slack app manifest for ${name} (generated by: mot manifest).`,
    '#',
    '# Create your app in one step:',
    '#   https://api.slack.com/apps -> "Create New App" -> "From a manifest"',
    '#   -> pick your workspace -> paste this file.',
    '#',
    '# The app runs in Socket Mode, so no public Request URL is needed. After',
    '# creating the app:',
    '#   1. Install it to your workspace (OAuth & Permissions -> Install to',
    '#      Workspace) and copy the Bot User OAuth Token (xoxb-...).',
    '#   2. Basic Information -> App-Level Tokens -> generate a token with the',
    '#      connections:write scope and copy it (xapp-...).',
    '#   3. Run `mot setup` and paste both tokens.',
    `#   4. Set SLASH_COMMAND=${command} in the gateway config (mot setup asks for it).`,
    '#',
    '# One Slack app per gateway: never share these tokens between two machines.',
    'display_information:',
    `  name: ${yamlScalar(name)}`,
    '  description: Chat with the pi coding agent from Slack — sessions, files, and scheduled tasks in any channel or DM',
    "  background_color: '#1a1d21'",
    'features:',
    '  app_home:',
    '    home_tab_enabled: false',
    '    # Without a writable Messages tab, users cannot DM the bot at all.',
    '    messages_tab_enabled: true',
    '    messages_tab_read_only_enabled: false',
    '  bot_user:',
    `    display_name: ${yamlScalar(botName)}`,
    '    always_online: true',
    '  slash_commands:',
    `    - command: ${command}`,
    `      description: ${yamlScalar(`Manage the ${name} session in this channel`)}`,
    "      usage_hint: '[status | model <ref> | models | reset-model | thinking <level> | new | stop]'",
    '      should_escape: false',
    'oauth_config:',
    '  scopes:',
    '    bot:',
    '      - chat:write',
    '      - channels:history',
    '      - groups:history',
    '      - im:history',
    '      - mpim:history',
    '      # conversations.info for auto-registered channel/group/mpim labels',
    '      - channels:read',
    '      - groups:read',
    '      - mpim:read',
    '      - files:read',
    '      - files:write',
    '      - reactions:write',
    '      - users:read',
    '      - commands',
    'settings:',
    '  event_subscriptions:',
    '    bot_events:',
    '      - message.channels',
    '      - message.groups',
    '      - message.im',
    '      - message.mpim',
    '  interactivity:',
    '    is_enabled: true',
    '  org_deploy_enabled: false',
    '  socket_mode_enabled: true',
    '  token_rotation_enabled: false',
    '',
  ].join('\n');
}
